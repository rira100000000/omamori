# frozen_string_literal: true

require_relative 'ai_settings'

module Omamori
  # The files `omamori init` and `omamori ci-setup` write. Provider names are not listed here:
  # whatever AISettings accepts (any RubyLLM provider, claude_code, codex) is written as given.
  module SetupFiles
    OMAMORIIGNORE = <<~IGNORE
      # Omamori ignore file
      # Add files and directories to ignore during Omamori scans.
      # Lines starting with # are comments.
      # Globs are supported (e.g., *.tmp, spec/fixtures/)
      # Negation with ! (e.g., !important.log) - not fully implemented in current basic matcher

      # Log files
      log/
      *.log

      # Temporary files
      tmp/
      *.tmp
      *.swp
      *.swo

      # OS-specific files
      .DS_Store
      Thumbs.db

      # Vendor directory (often contains third-party code)
      vendor/bundle/

      # Coverage reports
      coverage/

      # Node.js dependencies
      node_modules/

      # Build artifacts
      pkg/

      # Test files and fixtures (optional, consider if they contain sensitive examples)
      # spec/
      # test/
      # features/

      # Database schema and migrations (usually not directly exploitable via code injection)
      # db/schema.rb
      # db/migrate/

      # Assets (compiled or static, less likely to have Ruby vulnerabilities)
      # app/assets/builds/
      # public/assets/
    IGNORE

    # claude_code / codex use the CLI's login on the machine. omamori does not install or log in CLIs on
    # CI runners: their packages and login methods are theirs to change.
    CLI_IN_CI_NOTE = 'claude_code / codex need the CLI installed and logged in on the runner, which this ' \
                     'configuration does not do. Set that up yourself, or use an API reporter in CI ' \
                     '(add --reporter PROVIDER --reporter-model MODEL to the scan command).'

    module_function

    # settings: a resolved AISettings. language: e.g. "ja", or nil for the default (en)
    def omamorirc(settings, language: nil)
      <<~YAML
        # .omamorirc
        # Generated by `omamori init`. Check the setup with `omamori doctor`.

        # Reporter: the LLM that writes reports. Any RubyLLM provider (with a model),
        # or claude_code / codex to use a subscription CLI (claude -p / codex exec).
        #{role_yaml('reporter', settings.reporter.merge(fallback_hash(settings)))}
          # concurrency: 8           # Reports written in parallel (default 3 for CLIs, 8 for APIs)

        # Classifier (optional): a fast decision model that checks each risk as a yes/no question.
        # Only the flagged checks are sent to the reporter. Without it, the reporter checks everything.
        #{classifier_yaml(settings)}

        #{api_key_comment(settings)}

        # Language of the report details (default: en)
        #{language ? "language: #{language}" : '# language: ja'}

        # Security checks to run (optional; default: the 8 main checks without a classifier, all 35 with one)
        # checks:
        #   - xss
        #   - csrf
        #   - idor

        # Report output settings (optional)
        # report:
        #   output_path: ./omamori_report            # Prefix for html/json reports
        #   html_template: custom_report_template.erb

        # Static analyser options (optional)
        # static_analysers:
        #   brakeman:
        #     options: "--force"
        #   bundler_audit:
        #     options: "--quiet"

        # Chunk size for splitting large code content (optional, default: 8000 characters)
        # chunk_size: 10000

        # CI setup file paths (optional)
        # ci_setup:
        #   github_actions_path: .github/workflows/omamori_scan.yml
        #   gitlab_ci_path: .gitlab-ci.yml
      YAML
    end

    # What the user has to do outside omamori before scanning: one line per role
    def credential_steps(settings)
      roles(settings).map do |role, role_settings|
        provider = role_settings['provider']
        case provider
        when 'claude_code' then "#{role}: install Claude Code and log in (`claude`), or set ANTHROPIC_API_KEY"
        when 'codex' then "#{role}: install the Codex CLI and log in (`codex login`)"
        else
          env = AISettings.api_key_env(provider)
          env ? "#{role}: set #{env}" : "#{role}: set what RubyLLM needs for #{provider} (https://rubyllm.com)"
        end
      end
    end

    def github_actions(settings)
      <<~YAML
        # .github/workflows/omamori_scan.yml
        name: Omamori Security Scan

        on:
          push:
            branches: [ main, master ]
          pull_request:
            branches: [ main, master ]

        jobs:
          security_scan:
            runs-on: ubuntu-latest

            steps:
            - name: Checkout code
              uses: actions/checkout@v4
              with:
                fetch-depth: 0 # Needed to diff against the base branch

            - name: Set up Ruby
              uses: ruby/setup-ruby@v1 # Reads .ruby-version
              with:
                bundler-cache: true
        #{cli_note(settings, '    ')}
            - name: Run Omamori Scan
              env:
        #{env_lines(settings, indent: '        ') { |name| "        #{name}: ${{ secrets.#{name} }}" }}
              run: |
                if [ "$GITHUB_EVENT_NAME" == "pull_request" ]; then
                  bundle exec omamori scan --base "origin/$GITHUB_BASE_REF" --format console
                else
                  bundle exec omamori scan --all --format console
                fi
      YAML
    end

    def gitlab_ci(settings)
      <<~YAML
        # .gitlab-ci.yml
        stages:
          - security_scan

        omamori_security_scan:
          stage: security_scan
          image: ruby:3.3 # Use your project's Ruby version
          cache:
            key:
              files:
                - Gemfile.lock
            paths:
              - vendor/bundle
          before_script:
            - bundle config set --local path vendor/bundle
            - bundle install --jobs $(nproc) --retry 3
        #{cli_note(settings, '  ')}
          script:
            - |
              if [ "$CI_PIPELINE_SOURCE" == "merge_request_event" ]; then
                bundle exec omamori scan --base "origin/$CI_MERGE_REQUEST_TARGET_BRANCH_NAME" --format console
              else
                bundle exec omamori scan --all --format console
              fi
          # Set these as masked CI/CD variables in GitLab:
        #{env_lines(settings, indent: '  ') { |name| "  # #{name}" }}
          variables:
            GIT_DEPTH: "0" # Needed to diff against the target branch
          rules:
            - if: '$CI_COMMIT_BRANCH == $CI_DEFAULT_BRANCH'
            - if: '$CI_PIPELINE_SOURCE == "merge_request_event"'
      YAML
    end

    # [[role name, settings], ...] for the classifier, reporter and fallback reporter in use
    def roles(settings)
      [['classifier', settings.classifier], ['reporter', settings.reporter],
       ['reporter.fallback', settings.reporter_fallback]].select { |_, role_settings| role_settings }
    end

    def role_yaml(name, role_settings)
      lines = ["#{name}:"]
      role_settings.each do |key, value|
        if value.is_a?(Hash)
          lines << "  #{key}:"
          value.each { |sub_key, sub_value| lines << "    #{sub_key}: #{sub_value}" }
        else
          lines << "  #{key}: #{value}"
        end
      end
      lines.join("\n")
    end

    def classifier_yaml(settings)
      threshold = "  # threshold: #{AISettings::DEFAULT_THRESHOLD}            # Checks at or above this probability go to the reporter"
      return "#{role_yaml('classifier', settings.classifier)}\n#{threshold}" if settings.classifier?

      "# classifier:\n#   provider: typesafe        # typesafe / openai / ollama\n#   model: jev-1.13.0\n##{threshold[1..]}"
    end

    def fallback_hash(settings)
      settings.reporter_fallback ? { 'fallback' => settings.reporter_fallback } : {}
    end

    def api_key_comment(settings)
      names = roles(settings).filter_map { |_, role_settings| AISettings.api_key_env(role_settings['provider']) }.uniq
      return '# API keys are read from environment variables (PROVIDER_API_KEY, e.g. ANTHROPIC_API_KEY).' if names.empty?

      "# API keys are read from environment variables: #{names.join(', ')}"
    end

    def cli_providers(settings)
      roles(settings).map { |_, role_settings| role_settings['provider'] } & AISettings::CLI_REPORTERS
    end

    # API key environment variables the scan step needs
    def secret_names(settings)
      roles(settings).filter_map { |_, role_settings| AISettings.api_key_env(role_settings['provider']) }.uniq
    end

    def env_lines(settings, indent:, &format)
      names = secret_names(settings)
      return "#{indent}# Add the environment variables RubyLLM needs for your provider" if names.empty?

      names.map(&format).join("\n")
    end

    # A comment in the CI file when a role uses a subscription CLI
    def cli_note(settings, indent)
      return '' if cli_providers(settings).empty?

      "#{indent}# #{CLI_IN_CI_NOTE}"
    end
  end
end
